# Regenerates meridien/globe-dots.js: land dots on a near-equal-area lat/lon grid for the Méridien globe.
# Usage: python3 tools/build-globe-dots.py ne_110m_land.geojson ne_50m_land.geojson ne_10m_land.geojson
# Data: Natural Earth land (public domain). Output: base64 of Int16 pairs (lat*100, lon*100).
import base64, json, math, struct, sys

STEP = 1.15  # degrees between dots along a meridian

def rings(geom):
    polys = geom['coordinates'] if geom['type'] == 'MultiPolygon' else [geom['coordinates']]
    for poly in polys:
        yield poly[0], poly[1:]

def inside(x, y, ring):
    c = False; j = len(ring) - 1
    for i in range(len(ring)):
        xi, yi = ring[i]; xj, yj = ring[j]
        if (yi > y) != (yj > y) and x < (xj - xi) * (y - yi) / (yj - yi) + xi: c = not c
        j = i
    return c

land = json.load(open(sys.argv[1]))
polys = []
for f in land['features']:
    for outer, holes in rings(f['geometry']):
        xs = [p[0] for p in outer]; ys = [p[1] for p in outer]
        polys.append((outer, holes, (min(xs), min(ys), max(xs), max(ys))))

pts = []
lat = -58.0
while lat <= 82:
    n = max(1, round(360 * math.cos(math.radians(lat)) / STEP))
    for i in range(n):
        lon = -180 + (i + .5) * 360 / n
        for outer, holes, bb in polys:
            if bb[0] <= lon <= bb[2] and bb[1] <= lat <= bb[3] and inside(lon, lat, outer) and not any(inside(lon, lat, h) for h in holes):
                pts.append((round(lat * 100), round(lon * 100))); break
    lat += STEP

# Fine layers shown when the globe zooms in: Europe (1:50m data) and the Taiwan Strait (1:10m data)
FINE_LAYERS = [  # (box lon0, lat0, lon1, lat1), step in degrees, argv index of the source file
    ((-14.0, 33.0, 42.0, 63.0), .3, 2),
    ((112.0, 17.5, 129.0, 31.0), .16, 3),
]

def fine_layer(box, step, src):
    cand = []
    for f in json.load(open(src))['features']:
        for outer, holes in rings(f['geometry']):
            xs = [p[0] for p in outer]; ys = [p[1] for p in outer]
            bb = (min(xs), min(ys), max(xs), max(ys))
            if bb[0] < box[2] and bb[2] > box[0] and bb[1] < box[3] and bb[3] > box[1]:
                cand.append((outer, holes, bb))
    out = []
    lat = box[1]
    while lat <= box[3]:
        lon = box[0]
        while lon <= box[2]:
            for outer, holes, bb in cand:
                if bb[0] <= lon <= bb[2] and bb[1] <= lat <= bb[3] and inside(lon, lat, outer) and not any(inside(lon, lat, h) for h in holes):
                    out.append((round(lat * 100), round(lon * 100))); break
            lon += step / math.cos(math.radians(lat))
        lat += step
    return out

fine, boxes = [], []
for box, step, arg in FINE_LAYERS:
    if len(sys.argv) > arg:
        fine += fine_layer(box, step, sys.argv[arg]); boxes.append(list(box))

enc = lambda P: base64.b64encode(b''.join(struct.pack('<hh', a, b) for a, b in P)).decode()
open('meridien/globe-dots.js', 'w').write(
    '// Generated by tools/build-globe-dots.py from Natural Earth land (public domain): 1:110m world, finer layers for Europe and Taiwan.\n'
    '// Base64 of little-endian Int16 pairs: latitude × 100, longitude × 100.\n'
    f'export const GLOBE_DOTS = "{enc(pts)}";\n'
    f'export const FINE_BOXES = {json.dumps(boxes)};\n'
    f'export const FINE_DOTS = "{enc(fine)}";\n')
print(len(pts), 'dots,', len(fine), 'fine dots')
